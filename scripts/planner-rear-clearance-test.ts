import assert from 'node:assert/strict';
import {Road} from '../src/world/Road.ts';
import {ReferencePath} from '../src/world/ReferencePath.ts';
import {getTrack} from '../src/world/track.ts';
import {FrenetPlanner} from '../src/planner/FrenetPlanner.ts';
import {Simulation} from '../src/sim/Simulation.ts';
const path=new ReferencePath(getTrack().controlPoints,6),road=new Road(path,1),planner=new FrenetPlanner(road,{desiredSpeed:8});
const state={s:150,d:0,sDot:0,sDdot:0,dDot:0,dDdot:0,index:0};
const rear={s:145.5,d:0,v:0,vd:0,length:1.9,width:.82,kind:'car' as const};
const result=planner.plan(state,[rear],0,0);
assert(result.best&&!result.best.colliding&&result.best.targetSpeed>0,'stationary rear bike at a legal gap must allow pulling away');
const touching=planner.plan(state,[{...rear,s:148}],0,0);
assert(touching.candidates.every(c=>c.colliding),'real rear body overlap must remain a collision');
const front=planner.plan(state,[{...rear,s:154.5}],0,0);
assert(front.candidates.every(c=>c.colliding),'front stopping clearance must not be relaxed');
const sim=new Simulation({trackId:'two-way'});sim.setTrafficProfile('vietnam');
for(let i=0;i<180*60;i++)sim.step(1/60);
assert.equal(sim.metrics.collisions,0);assert(sim.metrics.distance>900,`one-lane flow stuck after ${sim.metrics.distance}m`);
console.log('PLANNER-REAR-CLEARANCE PASS — pull away from a stopped rear bike, retain physical/front constraints, three-minute two-way flow without contact.');
